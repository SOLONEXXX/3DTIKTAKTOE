const DICTS: Record<Language, Dict> = { de, en };

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const template = DICTS[language][key] ?? DICTS.de[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce((str, [k, v]) => str.replaceAll(`{${k}}`, String(v)), template);
}

/** Reactive translator hook — re-renders when the store's language changes. */
export function useT() {
  const language = useGameStore((s) => s.language);
  return (key: string, vars?: Record<string, string | number>) => translate(language, key, vars);
}
